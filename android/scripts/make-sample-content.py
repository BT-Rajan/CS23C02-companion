"""Builds the debug-only SAMPLE content package for the app (not book content).

    backend/.venv/bin/python android/scripts/make-sample-content.py

Uses the real package builder (content-tools) with a throwaway signing key, so the app's verifier is exercised exactly as with
server content. Writes android/app/src/debug/assets/sample-content/ and the matching public key into
android/app/src/debug/kotlin/.../SampleContent.kt. The private key is discarded: sample packages cannot be re-signed later, they
are rebuilt. Every code block's expected_output is checked with the stepper recorder first (book decision X2).
"""
import json
import pathlib
import shutil
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "content-tools"), str(ROOT / "runtime" / "stepper")]
from cs23c02_content import build  # noqa: E402
import stepper  # noqa: E402

SRC = ROOT / "content-tools" / "samples" / "reader-sample"
ASSETS = ROOT / "android" / "app" / "src" / "debug" / "assets" / "sample-content"
KOTLIN = ROOT / "android" / "app" / "src" / "debug" / "kotlin" / "app" / "cs23c02" / "companion" / "SampleContent.kt"


def check_code_blocks():
    for f in sorted((SRC / "lessons").glob("*.json")):
        for b in json.loads(f.read_text())["blocks"]:
            if b["type"] == "code":
                r = stepper.record(b["code"])
                assert r["status"] == "ok", (f.name, r["status"], r["error"])
                assert r["stdout"].rstrip("\n") == b.get("expected_output", "").rstrip("\n"), (f.name, r["stdout"])


def main():
    check_code_blocks()
    priv, pub = build.new_keypair()
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / "out"
        m = build.build(SRC, out, build.load_private(priv), signed_at="sample")
        if ASSETS.exists():
            shutil.rmtree(ASSETS)
        shutil.copytree(out / "public", ASSETS)
    KOTLIN.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN.write_text(f'''package app.cs23c02.companion

/** Generated by android/scripts/make-sample-content.py. Debug builds only: verifies the bundled SAMPLE package. */
object SampleContent {{
    const val PUBLIC_KEY = "{pub}"
    const val ASSET_DIR = "sample-content"
}}
''')
    print(f"sample package {m['book']['version']}: {len(m['files'])} files -> {ASSETS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
